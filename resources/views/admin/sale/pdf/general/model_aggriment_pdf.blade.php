     <p style="text-align: justify;">This agreement is executed on -------(Day)------(Month)-------(Year) for design, supply,
          installation, commissioning and 5-year comprehensive maintenance of RTS project/system
          along with warranty under PM Surya Ghar: Muft Bijli Yojana</p>

     <p style="text-align: center;"><b>Between</b></p>

     <p style="text-align: justify;"><u><b>{{$order_data->consumer_name}}</b></u> having address at <u><b>{{$order_data->address}}</b></u>
          (hereinafter referred to as first Party i.e. /consumer/consumer/purchaser /owner of system).</p>

     <p style="text-align: center;"><b>And</b></p>

     <p style="text-align: justify;"><u><b>{{ env('APP_NAME') }}</b></u> having registered office at <u><b>{{ env('APP_OWNER_ADDRESS_NO_BR') }}</b></u>
          (hereinafter referred to as second Party i.e. Vendor/ contractor/ System Integrator).</p>

     <p style="text-align: left;"><b>Whereas</b></p>

     <p style="text-align: justify;">First Party wishes to install a Grid Connected Rooftop Solar Plant on the rooftop of the residential
          building of the Consumer under PM Surya Ghar: Muft Bijli Yojana.</p>

     <p style="text-align: left;"><b>And whereas</b></p>

     <p style="text-align: justify;">Second Party has verified availability of appropriate roof and found it feasible to install a Grid
          Connected Roof Top Solar plant and that the second party is willing to design, supply, install, test, commission and carry out Operation & Maintenance of the Rooftop Solar plant for 5 year period</p>

     <p style="text-align: left;">On this day, the First Party and Second Party agree to the following:</p>

     <p style="text-align: left;"><u><b>The First Party hereby undertakes to perform the following activities:</b></u></p>

     <ul>
          <ol>
               <p style="text-align: justify;margin:0px !important;">1) Submission of online application at National Portal for installation of RTS project/system, Submission of application for net-metering and system inspection and upload of the relevant documents on the National Portal of the scheme</p>
          </ol>
          <ol>
               <p style="text-align: justify;margin:0px !important;">2) Provide secure storage of the material of the RTS plant delivered at the premises till handover of the system.</p>
          </ol>
          <ol>
               <p style="text-align: justify;margin:0px !important;">3) Provide access to the Roof Top during installation of the plant, operation & maintenance, testing of the plant and equipment and for meter reading from solar meter, inverter etc.</p>
          </ol>

          <div class="page-break"></div>

          <ol>
               <p style="text-align: justify;margin:0px !important;">4) Provide electricity during plant installation and water for cleaning of the panels.</p>
          </ol>
          <ol>
               <p style="text-align: justify;margin:0px !important;">5) Report any malfunctioning of the plant to the Vendor during the warranty period.</p>
          </ol>
          <ol>
               <p style="text-align: justify;margin:0px !important;">6) Pay the amount as per the payment schedule as mutually agreed with the vendor, including any additional amount to the second party for any additional work /customization required depending upon the building condition</p>
          </ol>
     </ul>

     <p style="text-align: left;"><u><b>The Second Party hereby undertakes to perform the following activities:</b></u></p>

     <ul>
          <ol>
               <p style="text-align: justify;margin:0px !important;">1. The Vendor must follow all the standards and safety guidelines prescribed under state regulations and technical standards prescribed by MNRE for RTS projects, failing which the vendor is liable for blacklisting from participation in the govt. project/ scheme and other penal actions in accordance with the law. The responsibility of supply, installation and commissioning of the rooftop solar projet/system in complete compliance with MNRE scheme guidelines lies with the Vendor.</p>
          </ol>
          <ol>
               <p style="text-align: justify;margin:0px !important;">2. <b>Site Survey:</b> Site visit, survey and development of detailed project report for installation of RTS system. This also includes, feasibility study of roof, strength of roof and shadow free area. If any additional work or customization is involved for the plant installation as per site condition and requirement of the consumer building, the Vendor shall prepare an estimate and can raise separate invoice including GST in addition to the amount towards standard plant cost. The consumer shall pay the amount for such additional work directly to the Vendor.</p>
          </ol>
          <ol>
               <p style="text-align: justify;margin:0px !important;">3. <b>Design & Engineering:</b> Design of plant along with drawings and selection of components as per standard provided by the DISCOM/SERC/MNRE for best performance and safety of the plant.</p>
          </ol>
          <ol>
               <p style="text-align: justify;margin:0px !important;">4. <b>Module and Inverter:</b> The solar modules, including the solar cells, should be manufactured in India. Both the solar modules and inverters shall conform to the relevant standards and specifications prescribed by MNRE. Any other requirement, viz. star labelling (solar modules), quality control orders and standards & labelling (inverters) etc., shall also be complied.</p>
          </ol>
          <ol>
               <p style="text-align: justify;margin:0px !important;">5. <b>Procurement & Supply:</b> Procurement of complete system as per BIS/IS/IEC standard (whatever applicable) & safety guidelines for installation of rooftop solar plants. The supplied materials should comply with all MNRE standards for release of subsidy.</p>
          </ol>
          <ol>
               <p style="text-align: justify;margin:0px !important;">6. <b>Installation & Civil work:</b> Complete civil work, structure work and electrical work (including drawings) following all the safety and relevant BIS standards.</p>
          </ol>

          <div class="page-break"></div>

          <ol>
               <p style="text-align: justify;margin:0px !important;">7. <b>Documentation (Technical Catalogues/Warranty Certificates/BIS certificates/other test reports etc): </b> All such documents shall be provided to the consumer for online uploading and submission of technical specifications, IEC/BIS report, Sr. Nos, Warranty card of Solar Panel & Inverter, Layout & Electrical SLD, Structure Design and Drawing, Cable and other detailed documents.</p>
          </ol>
          <ol>
               <p style="text-align: justify;margin:0px;">8. <b>Project completion report (PCR):</b> Assisting the consumer in filling and uploading of signed documents (Consumer & Vendor) on the national portal.</p>
          </ol>
          <ol>
               <p style="text-align: justify;margin:0px;">9. <b>Warranty:</b> System warranty certificates should be provided to the consumer. The complete system should be warranted for 5 years from the date of commissioning by DISCOM. Individual component warranty documents provided by the manufacturer shall be provided to the consumer and all possible assistance should be extended to the consumer for claiming the warranty from the manufacturer.</p>
          </ol>
          <ol>
               <p style="text-align: justify;margin:0px;">10. <b>NET meter & Grid Connectivity:</b> Net meter supply/procurement, testing and approvals shall be in the scope of vendor. Grid connection of the plant shall be in the scope of the vendor.</p>
          </ol>
          <ol>
               <p style="text-align: justify;margin:0px;">11. <b>Testing and Commissioning:</b> The vendor shall be present at the time of testing and commissioning by the DISCOM.</p>
          </ol>
          <ol>
               <p style="text-align: justify;margin:0px;">12. <b>Operation & Maintenance:</b> Five (5) years Comprehensive Operation and Maintenance including overhauling, wear and tear and regular checking of healthiness of system at proper interval shall be in the scope of vendor. The vendor shall also educate the consumer on best practices for cleaning of the modules and system maintenance.</p>
          </ol>
          <ol>
               <p style="text-align: justify;margin:0px;">13. <b>Insurance:</b> Any insurance cost pertaining to material transfer/storage before commissioning of the system shall be in the scope of the vendor.</p>
          </ol>
          <ol>
               <p style="text-align: justify;margin:0px;">14. <b>Applicable Standard:</b> The system must meet the technical standards and specifications notified by MNRE. The vendor is solely responsible to supply component and service which meets the technical standards and specification prescribed by MNRE and State DISCOMs.</p>
          </ol>
          <ol>
               <p style="text-align: justify;margin:0px;">15. <b>Project/system cost & payment terms:</b> The cost of the plant and payment schedule should be mutually discussed and decided between the vendor and consumer. The consumer may opt for milestone-based payment to the vendor and the same shall be included in the agreement.</p>
          </ol>
          <ol>
               <p style="text-align: justify;margin:0px;">16. <b>Dispute:</b> In-case of any dispute between consumer and vendor (in supply/installation/maintenance of system or payment terms), both parties must settle the same mutually or as per law. MNRE/DISCOM shall not be liable for, and would not be a party to any dispute arising between vendor and consumer.</p>
          </ol>

          <div class="page-break"></div>

          <ol>
               <p style="text-align: justify;margin:0px;">17. <b>Subsidy / Project Related Documents:</b> Vendor must provide all the documents to consumer and help in uploading the same to National Portal for smooth release of subsidy.</p>
          </ol>
          <ol>
               <p style="text-align: justify;margin:0px;">18. <b>Performance of Plant:</b> The Performance Ratio (PR) of Plant must be 75% at the time of commissioning of the project by DISCOM or its authorised agency. Vendor must provide (returnable basis) radiation sensor with valid calibration certificate of any NABL / International laboratory at the time of commissioning / testing of the plant. Vendor must maintain the PR of the plant till warranty of project i.e. 5 years from the date of commissioning.</p>
          </ol>
          <ol>
               <p style="text-align: justify;margin:0px;">19. <b>Mutually Agreed Terms of Payment …</b></p>
          </ol>
     </ul>

